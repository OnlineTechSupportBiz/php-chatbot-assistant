    /**
     * POST /chatbots/{id}/chat — Authenticated test chat for the dashboard.
     *
     * Expects JSON body: { "message": "..." }
     * Creates or reuses a test conversation for the admin user.
     */
    public function testChat(Request $req, Response $res, array $params): void
    {
        $user = Auth::requireAuth();
        Auth::requirePermission($user, 'test_chat');
        $adminId = (int) $user['admin_id'];
        $chatbotId = (int) ($params['id'] ?? 0);

        if ($chatbotId <= 0) {
            $res->json(['error' => 'Invalid chatbot ID'], 400)->send();
            return;
        }

        // Verify chatbot belongs to this admin account
        $chatbot = Chatbot::find($chatbotId);
        Auth::requireSameAdmin($user, $chatbot);

        $body = json_decode(file_get_contents('php://input'), true);
        $userMessage = trim($body['message'] ?? '');

        if ($userMessage === '') {
            $res->json(['error' => 'Message is required'], 400)->send();
            return;
        }

        // Use a stable test session ID tied to the user
        $visitorSessionId = 'test_' . $user['id'] . '_' . $chatbotId;

        try {
            $result = $this->processQuery($adminId, $chatbot, $visitorSessionId, $userMessage, $_SERVER['REMOTE_ADDR'] ?? null, userId: (int) $user['id']);
            $res->json($result)->send();
        } catch (\Throwable $e) {
            $res->json(['error' => $e->getMessage()], 500)->send();
        }
    }

    /**
     * POST /api/public/chat — Public chat endpoint for the embeddable widget.
     *
     * Expects JSON body: { "widget_token": "...", "message": "...", "session_id": "..." }
     * session_id is a UUID generated by the widget and stored in localStorage.
     */
    public function publicChat(Request $req, Response $res): void
    {
        // CORS preflight: allow from any origin (actual origin check happens below after chatbot lookup)
        header('Access-Control-Allow-Methods: POST, OPTIONS');
        header('Access-Control-Allow-Headers: Content-Type');

        if ($req->method === 'OPTIONS') {
            header('Access-Control-Allow-Origin: *');
            $res->setStatus(204)->send();
            return;
        }

        $body = json_decode(file_get_contents('php://input'), true);
        $widgetToken = trim($body['widget_token'] ?? '');
        $userMessage = trim($body['message'] ?? '');
        $visitorSessionId = trim($body['session_id'] ?? '');

        if ($widgetToken === '' || $userMessage === '' || $visitorSessionId === '') {
            $res->json(['error' => 'widget_token, message, and session_id are required'], 400)->send();
            return;
        }

        // Look up chatbot by widget token
        $chatbot = Chatbot::findByWidgetToken($widgetToken);
        if ($chatbot === null) {
            $res->json(['error' => 'Invalid or inactive chatbot'], 404)->send();
            return;
        }

        // ── CORS origin validation ───────────────────────────────────────
        $origin = $_SERVER['HTTP_ORIGIN'] ?? '';
        $host = $_SERVER['HTTP_HOST'] ?? '';
        $originAllowed = self::isOriginAllowed($origin, $chatbot['allowed_domains'] ?? null, $host);
        if (!$originAllowed) {
            $res->json(['error' => 'Origin not allowed'], 403)->send();
            return;
        }
        if ($origin !== '') {
            header('Access-Control-Allow-Origin: ' . $origin);
            header('Vary: Origin');
        }
        // Same-origin requests (no Origin header) do not need CORS headers.

        $permUserId = (int) ($chatbot['created_by'] ?? $chatbot['admin_id']);
        $adminId = (int) $chatbot['admin_id'];

        // Account active check — disabled users cannot serve widget requests
        $owner = \App\Model\User::find($permUserId);
        if (!$owner || empty($owner['is_active'])) {
            $res->json(['error' => 'Account disabled'], 403)->send();
            return;
        }

        // Endpoint toggle — widget owner can disable the widget
        if (!UserPermission::has($permUserId, 'widget_chat')) {
            $res->json(['error' => 'Chat widget is disabled for this account'], 403)->send();
            return;
        }

        // Check the user who owns this chatbot has API keys configured
        $keyOwnerId = (int) ($chatbot['created_by'] ?? $chatbot['admin_id']);
        $keys = Admin::getApiKeys($keyOwnerId);
        if (empty($keys['openai_api_key'])) {
            $res->json(['error' => 'Chatbot is not configured (missing API keys)'], 503)->send();
            return;
        }

        try {
            $result = $this->processQuery($adminId, $chatbot, $visitorSessionId, $userMessage, $_SERVER['REMOTE_ADDR'] ?? null, userId: $keyOwnerId);
            $res->json($result)->send();
        } catch (\Throwable $e) {
            $res->json(['error' => 'An error occurred processing your request'], 500)->send();
        }
    }

